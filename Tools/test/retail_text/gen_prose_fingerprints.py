#!/usr/bin/env python3
"""Generate Source/WoT/Tests/WoTRetailProseFingerprints.inl from the retail .int
files: one-way fingerprints of every retail prose string, so the
WoT.RetailText.NoCompiledProse spec can refuse compiled retail prose even in a
checkout that has no retail reference tree (the fingerprints are not text).

    python Tools/test/retail_text/gen_prose_fingerprints.py [--check]

Candidate rule (mirrors the spec): from every section of the bound packages,
Description / Quote / PickupMessage / LimitWarning values of 20+ characters and
any value of 48+ characters, whitespace runs collapsed to one space. A
fingerprint is (length, hash of the first 16 UTF-16 units, hash of all units),
hash h = h * 1000003 + unit (mod 2**64)."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "Tools"))
from wot_config import original_dir  # noqa: E402
PACKAGES = ("Engine", "WoT", "Angreal", "WoTTraps", "WoTPawns")
PROSE_KEYS = {"description", "quote", "pickupmessage", "limitwarning"}
WINDOW = 16
OUTPUT = REPO / "Source" / "WoT" / "Tests" / "WoTRetailProseFingerprints.inl"


def reference_dir() -> Path:
    return original_dir() / "System"


def parse_int(data: bytes) -> list[tuple[str, str, str]]:
    """UE1 FConfigFile::Read."""
    if data[:2] == b"\xff\xfe":
        text = data[2:].decode("utf-16-le")
    else:
        text = data.decode("latin-1")
    rows, section = [], None
    for line in text.replace("\r", "\n").split("\n"):
        if not line:
            continue
        if line[0] == "[" and line[-1] == "]":
            section = line[1:-1]
            continue
        if section is None or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if value and value[0] == '"' and value[-1] == '"':
            value = value[1:-1] if len(value) >= 2 else ""
        rows.append((section, key, value))
    return rows


def collapse(value: str) -> str:
    return " ".join(value.split())


def units(value: str) -> list[int]:
    raw = value.encode("utf-16-le")
    return [raw[i] | (raw[i + 1] << 8) for i in range(0, len(raw), 2)]


def poly(codes: list[int]) -> int:
    h = 0
    for code in codes:
        h = (h * 1000003 + code) & 0xFFFFFFFFFFFFFFFF
    return h


def candidates(directory: Path) -> list[str]:
    found: list[str] = []
    for package in PACKAGES:
        for _section, key, value in parse_int((directory / f"{package}.int").read_bytes()):
            text = collapse(value)
            if ((key.lower() in PROSE_KEYS and len(text) >= 20) or len(text) >= 48) \
                    and text not in found:
                found.append(text)
    return found


def fingerprints(values: list[str]) -> list[tuple[int, int, int]]:
    rows = set()
    for value in values:
        codes = units(value)
        rows.add((len(codes), poly(codes[:WINDOW]), poly(codes)))
    return sorted(rows)


def render(rows: list[tuple[int, int, int]]) -> str:
    lines = [
        "// GENERATED by Tools/test/retail_text/gen_prose_fingerprints.py - do not edit.",
        "// One-way fingerprints of the retail .int prose (length, 16-unit head hash,",
        "// full hash; h = h*1000003 + unit mod 2^64). Not text: WoT.RetailText.",
        "// NoCompiledProse refuses any Source/ span that matches one.",
        f"// {len(rows)} fingerprints.",
    ]
    lines += [f"{{{length}, 0x{head:016x}ull, 0x{full:016x}ull}},"
              for length, head, full in rows]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    directory = reference_dir()
    if not directory.is_dir():
        print(f"no retail reference tree at {directory}", file=sys.stderr)
        return 2
    text = render(fingerprints(candidates(directory)))
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"stale: {OUTPUT}", file=sys.stderr)
            return 1
        print(f"prose fingerprints OK: {OUTPUT}")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
