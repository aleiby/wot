#!/usr/bin/env python3
"""Compile the held-artifact pose CSV into C++ rows; Python 3.9, stdlib only."""
import argparse
import csv
import io
import math
import pathlib
import re
import sys

PLUGIN = pathlib.Path(__file__).resolve().parents[2] / "Plugins" / "WoTFirstPerson"
COLUMNS = "Class,OffsetX,OffsetY,OffsetZ,Pitch,Yaw,Roll,ScaleMultiplier".split(",")


def render(source):
    reader = csv.DictReader(io.StringIO(source))
    if reader.fieldnames != COLUMNS:
        raise ValueError("pose columns must be " + ",".join(COLUMNS))
    rows = {}
    for line, row in enumerate(reader, 2):
        name = row["Class"].strip()
        if name != "*" and not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", name):
            raise ValueError("line %d: invalid class key" % line)
        if name.casefold() in rows:
            raise ValueError("line %d: duplicate class key" % line)
        if None in row or any(value is None for value in row.values()):
            raise ValueError("line %d: wrong column count" % line)
        values = [float(row[key]) for key in COLUMNS[1:]]
        if not all(math.isfinite(value) for value in values):
            raise ValueError("line %d: pose values must be finite" % line)
        if values[0] <= 0 or values[-1] <= 0:
            raise ValueError("line %d: forward offset and scale must be positive" % line)
        rows[name.casefold()] = (name, values)
    if "*" not in rows:
        raise ValueError("exactly one default (*) pose is required")
    result = ["// Generated by Tools/import/generate_held_artifact_poses.py; edit Plugins/WoTFirstPerson/Data/held_artifact_poses.csv."]
    for key in sorted(rows):
        name, values = rows[key]
        numbers = [repr(value if value != 0 else 0.0) for value in values]
        result.append('{TEXT("%s"), FVector(%s), FRotator(%s), %sf},' % (
            name, ", ".join(numbers[:3]), ", ".join(numbers[3:6]), numbers[6]))
    return "\n".join(result) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=pathlib.Path,
                        default=PLUGIN / "Data/held_artifact_poses.csv")
    parser.add_argument("--output", type=pathlib.Path, default=PLUGIN /
                        "Source/WoTFirstPerson/Private/Generated/WoTHeldArtifactPoses.inl")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        expected = render(args.input.read_text(encoding="utf-8-sig")).encode("utf-8")
        current = args.output.read_bytes() if args.output.exists() else None
        if args.check:
            if current != expected:
                raise ValueError("generated pose rows are stale")
        elif current != expected:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(expected)
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
