#!/usr/bin/env python3
"""Embed the setup screen's default backdrop in a generated C++ include.

The setup screen draws a blurred image of the main-menu scene behind its
progress. Until the player's own capture exists (it is written the first time
the main menu shows), the game uses a default made the same way. The default
is compiled into the game as a byte array rather than staged as a loose file
or cooked as an asset, so it ships in every build configuration without a
packaging rule.

The committed PNG is the source of truth. This tool writes the include from
it; ``--check`` (and test_generate_setup_backdrop.py) fails when the committed
include no longer matches the committed PNG.

    python Tools/build/generate_setup_backdrop.py           # regenerate
    python Tools/build/generate_setup_backdrop.py --check   # verify only

Standard library only; Python 3.9 compatible. The output is deterministic and
always uses LF line endings.
"""
from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PNG_RELATIVE = "Source/WoT/UI/Resources/WoTSetupBackdropDefault.png"
OUTPUT_RELATIVE = "Source/WoT/UI/Generated/WoTSetupBackdropDefault.inl"
# WoTSetupBackdrop::Width x Height; the game refuses any other size.
WIDTH = 640
HEIGHT = 360
# The game refuses a backdrop PNG larger than this (WoTSetupBackdrop.cpp).
MAX_BYTES = 1024 * 1024
BYTES_PER_LINE = 16
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


class BackdropError(ValueError):
    """The PNG is not one the game would accept as its backdrop."""


def png_size(data: bytes) -> tuple[int, int]:
    """The width and height the PNG's IHDR chunk declares."""
    if (len(data) < 24 or not data.startswith(PNG_SIGNATURE)
            or data[12:16] != b"IHDR"):
        raise BackdropError("not a PNG")
    width, height = struct.unpack(">II", data[16:24])
    return width, height


def validate(data: bytes) -> None:
    if not data:
        raise BackdropError("the PNG is empty")
    if len(data) > MAX_BYTES:
        raise BackdropError(
            f"the PNG is {len(data)} bytes; the game refuses more than {MAX_BYTES}")
    size = png_size(data)
    if size != (WIDTH, HEIGHT):
        raise BackdropError(
            f"the PNG is {size[0]}x{size[1]}; the backdrop must be {WIDTH}x{HEIGHT}")


def render(data: bytes) -> bytes:
    """The include for ``data``: identical input always gives identical bytes."""
    validate(data)
    lines = [
        "// Generated by Tools/build/generate_setup_backdrop.py; do not edit.",
        f"// Source: {PNG_RELATIVE}",
        f"// SHA-256: {hashlib.sha256(data).hexdigest()}",
        "//",
        "// The setup screen's default backdrop (a blurred capture of the main-menu",
        "// scene), shown until the player's own capture exists. Included once, by",
        "// WoTSetupBackdrop.cpp, which decodes it like a saved capture.",
        "#pragma once",
        "",
        "namespace WoTSetupBackdropDefault",
        "{",
        f"static constexpr int32 PngSize = {len(data)};",
        "static const uint8 Png[] = {",
    ]
    for start in range(0, len(data), BYTES_PER_LINE):
        chunk = data[start:start + BYTES_PER_LINE]
        lines.append("\t" + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.extend(["};", "}", ""])
    return "\n".join(lines).encode("ascii")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Embed the setup screen's default backdrop PNG as C++ bytes.")
    parser.add_argument("--png", type=Path, default=REPO / PNG_RELATIVE)
    parser.add_argument("--output", type=Path, default=REPO / OUTPUT_RELATIVE)
    parser.add_argument("--check", action="store_true",
                        help="fail when the output does not match the PNG")
    args = parser.parse_args(argv)
    try:
        expected = render(args.png.read_bytes())
        if args.check:
            actual = args.output.read_bytes() if args.output.is_file() else None
            if actual != expected:
                print(f"setup backdrop include is stale: {args.output}; "
                      "regenerate with Tools/build/generate_setup_backdrop.py",
                      file=sys.stderr)
                return 1
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(expected)
    except (BackdropError, OSError) as exc:
        print(f"setup backdrop: {exc}", file=sys.stderr)
        return 2
    print(f"setup backdrop include OK: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
