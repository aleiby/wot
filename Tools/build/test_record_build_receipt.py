#!/usr/bin/env python3
"""Specs for the guarded build receipt.

The point of the receipt is that it REFUSES a build whose compiled definitions
do not match its configuration, so most of these are rejection cases.
"""
from __future__ import annotations

import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import record_build_receipt as receipt


GUARDED = ["WOT_GUARDED_BOOTSTRAP 1"]
TEST_ONLY = ["WOT_BOOTSTRAP_TEST_IDENTITIES 1", "WOT_BOOTSTRAP_TEST_ENDPOINTS 1"]


def make_tree(root: Path, target: str, configuration: str, defines: list[str],
              modules: tuple[str, ...] = ("Core", "Engine")) -> Path:
    project = root / "WoT.uproject"
    project.write_text("{}")
    for module in modules:
        directory = (root / "Intermediate" / "Build" / "Mac" / "arm64" /
                     target / configuration / module)
        directory.mkdir(parents=True, exist_ok=True)
        body = "".join(f"#define {d}\n" for d in defines)
        (directory / "Definitions.h").write_text(
            "// generated by UBT\n#pragma once\n" + body)
    return project


class RecordBuildReceiptTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        self.addCleanup(self._tmp.cleanup)

    def run_tool(self, project: Path, target: str, configuration: str):
        out = self.root / "receipt.json"
        code = receipt.main([
            "--project", str(project), "--target", target, "--platform", "Mac",
            "--configuration", configuration, "--out", str(out)])
        return code, out

    def test_test_configuration_records_and_accepts(self):
        project = make_tree(self.root, "WoT", "Test", GUARDED + TEST_ONLY)
        code, out = self.run_tool(project, "WoT", "Test")
        self.assertEqual(code, 0)
        document = json.loads(out.read_text())
        self.assertEqual(document["format"], receipt.RECEIPT_FORMAT)
        self.assertEqual(document["configuration"], "Test")
        self.assertEqual(document["definitions"]["WOT_BOOTSTRAP_TEST_IDENTITIES"], "1")
        self.assertIn("test-only-definitions-present", document["checks"])

    def test_guarded_crash_reporter_profile_is_recorded(self):
        # build_stripped_pak.py's guarded Test check needs these three in the
        # receipt; they are not WOT_* names.
        project = make_tree(self.root, "WoT", "Test", GUARDED + TEST_ONLY + [
            "NOINITCRASHREPORTER 1", "CRASH_REPORTER_WITH_ANALYTICS 0",
            "USE_CRASH_REPORTER_MONITOR 0", "UNRELATED_ENGINE_DEFINE 1"])
        code, out = self.run_tool(project, "WoT", "Test")
        self.assertEqual(code, 0)
        definitions = json.loads(out.read_text())["definitions"]
        self.assertEqual(definitions["NOINITCRASHREPORTER"], "1")
        self.assertEqual(definitions["CRASH_REPORTER_WITH_ANALYTICS"], "0")
        self.assertEqual(definitions["USE_CRASH_REPORTER_MONITOR"], "0")
        self.assertNotIn("UNRELATED_ENGINE_DEFINE", definitions)

    def test_shipping_without_test_definitions_accepts(self):
        project = make_tree(self.root, "WoT", "Shipping", GUARDED)
        code, out = self.run_tool(project, "WoT", "Shipping")
        self.assertEqual(code, 0)
        document = json.loads(out.read_text())
        self.assertIn("test-only-definitions-absent", document["checks"])
        self.assertNotIn("WOT_BOOTSTRAP_TEST_IDENTITIES", document["definitions"])

    def test_shipping_carrying_a_test_definition_is_rejected(self):
        project = make_tree(self.root, "WoT", "Shipping", GUARDED + TEST_ONLY)
        code, _ = self.run_tool(project, "WoT", "Shipping")
        self.assertEqual(code, 1)

    def test_test_missing_a_test_definition_is_rejected(self):
        project = make_tree(self.root, "WoT", "Test",
                            GUARDED + ["WOT_BOOTSTRAP_TEST_IDENTITIES 1"])
        code, _ = self.run_tool(project, "WoT", "Test")
        self.assertEqual(code, 1)

    def test_guarded_configuration_without_the_guard_is_rejected(self):
        project = make_tree(self.root, "WoT", "Test", TEST_ONLY)
        code, _ = self.run_tool(project, "WoT", "Test")
        self.assertEqual(code, 1)


    def test_development_must_not_be_guarded(self):
        project = make_tree(self.root, "WoT", "Development", GUARDED)
        code, _ = self.run_tool(project, "WoT", "Development")
        self.assertEqual(code, 1)

    def test_missing_build_is_rejected_rather_than_reported_empty(self):
        project = self.root / "WoT.uproject"
        project.write_text("{}")
        (self.root / "Intermediate" / "Build" / "Mac").mkdir(parents=True)
        code, _ = self.run_tool(project, "WoT", "Test")
        self.assertEqual(code, 1)

    def test_conflicting_values_across_modules_are_rejected(self):
        project = make_tree(self.root, "WoT", "Test", GUARDED + TEST_ONLY,
                            modules=("Core",))
        other = (self.root / "Intermediate" / "Build" / "Mac" / "arm64" /
                 "WoT" / "Test" / "Engine")
        other.mkdir(parents=True)
        (other / "Definitions.h").write_text(
            "#define WOT_GUARDED_BOOTSTRAP 0\n")
        code, _ = self.run_tool(project, "WoT", "Test")
        self.assertEqual(code, 1)

    def test_a_guarded_by_definition_target_may_be_guarded_in_development(self):
        # Regression: keying "guarded" off configuration alone made a Development
        # build of the guarded-engine harness unreceiptable, rejecting the very
        # thing that target exists to exercise. Found by the Windows lane.
        project = make_tree(self.root, "WoTGuardedEngineTests", "Development", GUARDED)
        code, out = self.run_tool(project, "WoTGuardedEngineTests", "Development")
        self.assertEqual(code, 0)
        document = json.loads(out.read_text())
        self.assertIn("guarded-by-target-definition", document["checks"])
        self.assertIn("guard-definitions-present", document["checks"])

    def test_a_guarded_by_definition_target_must_still_be_guarded(self):
        project = make_tree(self.root, "WoTGuardedEngineTests", "Development", [])
        code, _ = self.run_tool(project, "WoTGuardedEngineTests", "Development")
        self.assertEqual(code, 1)

    def test_a_guarded_by_definition_target_still_rejects_test_definitions(self):
        project = make_tree(self.root, "WoTGuardedEngineTests", "Development",
                            GUARDED + TEST_ONLY)
        code, _ = self.run_tool(project, "WoTGuardedEngineTests", "Development")
        self.assertEqual(code, 1)

    def test_an_ordinary_target_is_still_not_guarded_in_development(self):
        project = make_tree(self.root, "WoT", "Development", GUARDED)
        code, _ = self.run_tool(project, "WoT", "Development")
        self.assertEqual(code, 1)

    def test_a_named_test_harness_may_carry_test_definitions_in_development(self):
        project = make_tree(
            self.root, "WoTUpdateTransportsTests", "Development", TEST_ONLY)
        code, out = self.run_tool(
            project, "WoTUpdateTransportsTests", "Development")
        self.assertEqual(code, 0)
        self.assertIn("test-harness-target-allowance",
                      json.loads(out.read_text())["checks"])

    def test_transport_test_harness_may_carry_endpoint_seam_in_development(self):
        project = make_tree(
            self.root, "WoTUpdateTransportsTests", "Development",
            ["WOT_BOOTSTRAP_TEST_ENDPOINTS 1"])
        code, out = self.run_tool(
            project, "WoTUpdateTransportsTests", "Development")
        self.assertEqual(code, 0)
        self.assertIn("test-harness-target-allowance",
                      json.loads(out.read_text())["checks"])

    def test_the_harness_allowance_never_extends_to_shipping(self):
        # The rule these definitions exist to enforce is "never in a shipped
        # image", so no target is excused in Shipping.
        project = make_tree(
            self.root, "WoTUpdateTransportsTests", "Shipping", TEST_ONLY)
        code, _ = self.run_tool(
            project, "WoTUpdateTransportsTests", "Shipping")
        self.assertEqual(code, 1)

    def test_an_unnamed_target_gets_no_harness_allowance(self):
        project = make_tree(self.root, "SomeOtherTests", "Development", TEST_ONLY)
        code, _ = self.run_tool(project, "SomeOtherTests", "Development")
        self.assertEqual(code, 1)

    def test_engine_receipt_is_folded_in(self):
        project = make_tree(self.root, "WoT", "Test", GUARDED + TEST_ONLY)
        engine_receipt = self.root / "engine.json"
        engine_receipt.write_text(json.dumps(
            {"commit": "abc123", "tag": "5.8.0-release", "checks": ["commit-matches-pin"],
             "toolchain": {"apple_clang": "17"}, "ignored": "dropped"}))
        out = self.root / "receipt.json"
        code = receipt.main([
            "--project", str(project), "--target", "WoT", "--platform", "Mac",
            "--configuration", "Test", "--engine-receipt", str(engine_receipt),
            "--out", str(out)])
        self.assertEqual(code, 0)
        document = json.loads(out.read_text())
        self.assertEqual(document["engine"]["commit"], "abc123")
        self.assertNotIn("ignored", document["engine"])

    def test_a_named_engine_receipt_that_is_missing_is_rejected(self):
        project = make_tree(self.root, "WoT", "Test", GUARDED + TEST_ONLY)
        out = self.root / "receipt.json"
        code = receipt.main([
            "--project", str(project), "--target", "WoT", "--platform", "Mac",
            "--configuration", "Test",
            "--engine-receipt", str(self.root / "absent.json"), "--out", str(out)])
        self.assertEqual(code, 1)


if __name__ == "__main__":
    unittest.main()
